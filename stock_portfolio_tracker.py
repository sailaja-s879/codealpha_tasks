# CodeAlpha Task 2: Stock Portfolio Tracker

import csv

# Predefined stock prices
stock_prices = {
    "AAPL": 180,
    "TSLA": 250,
    "GOOGL": 150,
    "MSFT": 420,
    "AMZN": 190
}

portfolio = []
total_investment = 0

print("=" * 40)
print("       STOCK PORTFOLIO TRACKER")
print("=" * 40)

print("\nAvailable Stocks:")
for stock, price in stock_prices.items():
    print(f"{stock}: ${price}")

# Get stock details from the user
while True:
    stock_name = input(
        "\nEnter stock name (or 'done' to finish): "
    ).strip().upper()

    if stock_name == "DONE":
        break

    if stock_name not in stock_prices:
        print("Invalid stock name. Please try again.")
        continue

    try:
        quantity = int(input("Enter quantity: "))

        if quantity <= 0:
            print("Quantity must be greater than zero.")
            continue

    except ValueError:
        print("Please enter a valid whole number.")
        continue

    price = stock_prices[stock_name]
    investment = price * quantity

    total_investment += investment

    portfolio.append({
        "Stock": stock_name,
        "Price": price,
        "Quantity": quantity,
        "Investment": investment
    })

    print(f"{stock_name} investment: ${investment:.2f}")

# Display portfolio summary
print("\n" + "=" * 40)
print("           PORTFOLIO SUMMARY")
print("=" * 40)

if portfolio:
    for item in portfolio:
        print(
            f"{item['Stock']} | "
            f"Price: ${item['Price']:.2f} | "
            f"Quantity: {item['Quantity']} | "
            f"Value: ${item['Investment']:.2f}"
        )

    print("-" * 40)
    print(f"TOTAL INVESTMENT: ${total_investment:.2f}")

    # Save results to a CSV file
    with open("stock_portfolio.csv", "w", newline="") as file:
        fieldnames = [
            "Stock", "Price", "Quantity", "Investment"
        ]

        writer = csv.DictWriter(
            file, fieldnames=fieldnames
        )

        writer.writeheader()
        writer.writerows(portfolio)

    print("\nPortfolio saved to stock_portfolio.csv")

else:
    print("No stocks were added to the portfolio.")

print("\nThank you for using Stock Portfolio Tracker!")